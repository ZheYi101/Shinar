"""Runtime-generated Python bytecode must not invalidate the base interpreter."""

import hashlib
import io
import json
import tarfile

import httpx
import pytest

from shinar.local_speech.catalog import Artifact, ModelPackage
from shinar.local_speech.downloads import ModelStore, is_volatile_python_file
from shinar.local_speech.storage import atomic_json


FILES = {
    "python.exe": b"managed python executable",
    "python312.dll": b"managed python DLL",
    "Lib/example.py": b"print('source identity')\n",
    "Lib/__pycache__/example.cpython-312.pyc": b"bundled bytecode",
    "Lib/legacy.pyo": b"bundled optimized bytecode",
}
BYTECODE = tuple(name for name in FILES if name.endswith((".pyc", ".pyo")))


@pytest.fixture
def python_resource():
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w:gz") as archive:
        for name, content in FILES.items():
            member = tarfile.TarInfo("python/" + name)
            member.size = len(content)
            archive.addfile(member, io.BytesIO(content))
    content = output.getvalue()
    item = Artifact(path="python.tar.gz", url="https://models.example/python.tar.gz",
                    size=len(content), sha256=hashlib.sha256(content).hexdigest(),
                    archive_root="python", unpacked_limit=1024 * 1024)
    package = ModelPackage(
        id="speech-resource-python-31213", revision="locked-v1", name="managed Python",
        task="runtime", adapter="resource", languages=[], scenarios=["conversation"],
        streaming="none", license_note="fixture", sources=["https://models.example"],
        files=[item], required_files=["python.exe"], notes="fixture",
    )
    return package, content


def install(root, package, content):
    store = ModelStore(root)
    with httpx.Client(transport=httpx.MockTransport(
        lambda request: httpx.Response(200, content=content)
    )) as client:
        return store, store.install(package, client=client)


def old_receipt(directory, package):
    inventory = {name: {"size": len(content), "sha256": hashlib.sha256(content).hexdigest()}
                 for name, content in FILES.items()}
    atomic_json(directory / ".installed.json", {"fingerprint": package.fingerprint, "files": inventory})


def test_new_python_receipt_excludes_only_regenerable_bytecode(tmp_path, python_resource):
    package, content = python_resource
    store, directory = install(tmp_path, package, content)
    marker = json.loads((directory / ".installed.json").read_text())
    assert marker["fingerprint"] == package.fingerprint
    assert set(marker["files"]) == set(FILES) - set(BYTECODE)
    for name in BYTECODE:
        (directory / name).write_bytes(b"regenerated bytecode of a different size")
    assert store.installed(package)
    assert store.verify(package)


@pytest.mark.parametrize("change", ["different-size", "same-size", "removed"])
def test_legacy_python_receipt_ignores_changed_bytecode_without_rewriting_or_reinstalling(
    tmp_path, python_resource, change
):
    package, content = python_resource
    store, directory = install(tmp_path, package, content)
    old_receipt(directory, package)
    receipt = (directory / ".installed.json").read_bytes()
    for name in BYTECODE:
        path = directory / name
        if change == "removed":
            path.unlink()
        else:
            path.write_bytes(b"x" * (len(FILES[name]) if change == "same-size" else 1))
    assert store.installed(package)
    assert store.verify(package)
    with httpx.Client(transport=httpx.MockTransport(
        lambda request: pytest.fail("interpreter must not be downloaded again")
    )) as client:
        assert store.install(package, client=client) == directory
    assert (directory / ".installed.json").read_bytes() == receipt
    assert not tuple(directory.parent.glob("*.invalid-*"))


@pytest.mark.parametrize("name", ["python.exe", "python312.dll", "Lib/example.py"])
@pytest.mark.parametrize("size_changed", [False, True])
def test_python_source_dll_and_executable_remain_strictly_verified(
    tmp_path, python_resource, name, size_changed
):
    package, content = python_resource
    store, directory = install(tmp_path, package, content)
    old_receipt(directory, package)
    original = FILES[name]
    (directory / name).write_bytes(b"x" * (len(original) + int(size_changed)))
    if size_changed:
        assert not store.installed(package)
    with pytest.raises(ValueError, match="不完整|损坏"):
        store.verify(package)


@pytest.mark.parametrize("identity,task,adapter", [
    ("test-model", "stt", "sensevoice"),
    ("speech-resource-other", "runtime", "resource"),
    ("speech-resource-python-model", "stt", "sensevoice"),
])
def test_non_python_packages_keep_bytecode_inside_their_strict_receipts(
    tmp_path, python_resource, identity, task, adapter
):
    package, content = python_resource
    package = package.model_copy(update={"id": identity, "task": task, "adapter": adapter})
    store, directory = install(tmp_path, package, content)
    marker = json.loads((directory / ".installed.json").read_text())
    assert set(marker["files"]) == set(FILES)
    name = BYTECODE[0]
    (directory / name).write_bytes(b"x" * len(FILES[name]))
    with pytest.raises(ValueError, match="损坏"):
        store.verify(package)


def test_explicitly_required_python_bytecode_is_not_exempt(tmp_path, python_resource):
    package, content = python_resource
    name = BYTECODE[0]
    package = package.model_copy(update={"required_files": ["python.exe", name]})
    assert not is_volatile_python_file(package, name)
    store, directory = install(tmp_path, package, content)
    marker = json.loads((directory / ".installed.json").read_text())
    assert name in marker["files"]
    (directory / name).unlink()
    assert not store.installed(package)
    with pytest.raises(ValueError, match="不完整"):
        store.verify(package)
