"""The call collaborators receive capabilities, not a desktop controller."""

from collections.abc import Awaitable, Callable, MutableMapping
from pathlib import Path
from typing import Any, Protocol

from shinar.desktop.presentation.conversation_presentation import ConversationEvent, PresentationToken


class CallRuntimePort(Protocol):
    root: Path
    bridge: Any
    process: Any
    runner: Any
    worker: Any
    capture_pending: int
    timings: dict[str, float]

    @property
    def voice_pending(self) -> bool: ...
    @property
    def operation_busy(self) -> bool: ...
    @property
    def session_active(self) -> bool: ...
    @property
    def workbench(self) -> Any: ...
    @property
    def draft(self) -> str: ...
    @property
    def draft_revision(self) -> int: ...
    @property
    def pause_ms(self) -> int: ...
    @property
    def turn_errors(self) -> MutableMapping[str, str]: ...
    @property
    def speech_errors(self) -> MutableMapping[str, str]: ...
    @property
    def speech_error_codes(self) -> MutableMapping[str, str]: ...

    def notify(self) -> None: ...
    def components_changed(self) -> None: ...
    def storage_changed(self) -> None: ...
    def source(self) -> Any: ...
    def language(self) -> str: ...
    def speak_enabled(self) -> bool: ...
    def suspend_preflight(self) -> None: ...
    def route(self, task: str) -> Any: ...
    def new_token(self, task: str) -> PresentationToken: ...
    def confirm(
        self, token: PresentationToken, turn: str, session: Any, draft: Any
    ) -> PresentationToken: ...
    def present(self, event: ConversationEvent) -> bool: ...
    def emit(self, identity: str, kind: str, value: Any = None, generation: int = 0) -> None: ...
    def post(self, operation: Callable[[], Awaitable[Any]]) -> str: ...
    def request_permission(
        self, continuation: Callable[[], None], *, starting: bool = False
    ) -> None: ...
    def new_bridge(self) -> Any: ...
    def create_process(self, identity: str) -> Any: ...
    def vad(self) -> Path: ...
    def record_fault(self, code: str | None, *, stage: str | None = None) -> None: ...
    async def aclose(self) -> None: ...
